# Minimal primary model using aggregate data only; no sf/shapefile dependency.
suppressPackageStartupMessages({library(INLA);library(jsonlite)})
args<-commandArgs(trailingOnly=TRUE)
root<-if(length(args))normalizePath(args[1],mustWork=TRUE) else getwd()
d<-read.csv(file.path(root,'data/panel.csv'),stringsAsFactors=FALSE)
cfg<-fromJSON(file.path(root,'data/config.json'))
nodes<-read.csv(file.path(root,'data/node_order.csv'),stringsAsFactors=FALSE)
g<-inla.read.graph(file.path(root,'data/graph.graph'))
stopifnot(nrow(nodes)==229,g$n==229,identical(nodes$area,seq_len(229L)),!anyDuplicated(nodes$fbd_region))
d$area<-match(d$fbd_region,nodes$fbd_region);d$time<-d$year-min(d$year)+1L;d$yiid<-d$time;d$id<-seq_len(nrow(d))
v<-unique(c(cfg$sets_after_vif[[cfg$rules$main_set]],cfg$forced))
stopifnot(length(v)==24,nrow(d)==3206,!anyNA(d$area),all(is.finite(d$E)),all(d$E>0),!anyNA(d[,v]))
X<-model.matrix(reformulate(v),d);stopifnot(qr(X)$rank==25)
pc<-list(prec=list(prior='pc.prec',param=c(0.5,0.01)),phi=list(prior='pc',param=c(0.5,2/3)))
pcp<-list(prec=list(prior='pc.prec',param=c(0.5,0.01)))
CF<-list(mean=0,prec=4,mean.intercept=0,prec.intercept=0.001)
form<-as.formula(paste('cases ~ 1 +',paste(sprintf('`%s`',v),collapse=' + '),"+ f(area,model='bym2',graph=g,scale.model=TRUE,constr=TRUE,hyper=pc) + f(time,model='rw1',scale.model=TRUE,hyper=pcp) + f(yiid,model='iid',hyper=pcp)"))
# Validation-only is the default. Use --fit and a new output directory explicitly.
if('--fit'%in%args){
 i<-match('--fit',args);stopifnot(length(args)>i);out<-args[i+1];stopifnot(!dir.exists(out),!file.exists(out));dir.create(out,recursive=TRUE)
 inla.setOption(num.threads='1:1')
 m<-inla(form,family='nbinomial',data=d,E=d$E,control.fixed=CF,control.compute=list(dic=TRUE,waic=TRUE,cpo=TRUE,config=FALSE),control.inla=list(control.vb=list(emergency=50)),verbose=FALSE)
 writeLines(toJSON(list(ok=m$ok,mode_status=m$mode$mode.status,misc_mode_status=m$misc$mode.status,internal_warnings=m$misc$warnings,fixed_finite=all(is.finite(as.matrix(m$summary.fixed))),hyper_finite=all(is.finite(as.matrix(m$summary.hyperpar))),WAIC=m$waic$waic),auto_unbox=TRUE,null='null',pretty=TRUE),file.path(out,'diagnostics.json'))
 z<-m$summary.fixed;write.csv(data.frame(term=rownames(z),beta=z$mean,IRR=exp(z$mean),lo=exp(z$`0.025quant`),hi=exp(z$`0.975quant`),credible=z$`0.025quant`>0|z$`0.975quant`<0),file.path(out,'primary_estimates.csv'),row.names=FALSE)
 saveRDS(m,file.path(out,'primary.rds'));writeLines(capture.output(sessionInfo()),file.path(out,'sessionInfo.txt'))
} else cat('Inputs and design valid; no fit performed.\n')
